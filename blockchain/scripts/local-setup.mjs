import fs from 'node:fs';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { ContractFactory, JsonRpcProvider, Wallet, keccak256 } from 'ethers';
import { compile } from './compile.mjs';
import { LOCAL_DIR, LOCAL_RPC, localSecrets, repo } from './local-chain.mjs';

// Deploys StudyCoin once to the running local chain and writes the backend env file for it.
// Run `node blockchain/scripts/local-chain.mjs` in another window first.
const s = localSecrets(), record = path.join(LOCAL_DIR, 'deployment.json'), envFile = path.join(repo, '.local', 'rewards-local.env');
const provider = new JsonRpcProvider(LOCAL_RPC, undefined, { cacheTimeout: -1 });
try {
  try { if ((await provider.getNetwork()).chainId !== 31337n) throw new Error('Not the local chain (31337).'); }
  catch (e) { throw new Error(`Local chain is not reachable at ${LOCAL_RPC}. Start blockchain/scripts/local-chain.mjs first. (${e.message})`); }
  const compiled = compile();
  let deployment = fs.existsSync(record) ? JSON.parse(fs.readFileSync(record, 'utf8')) : null;
  if (deployment && keccak256(await provider.getCode(deployment.contract)) !== keccak256(compiled.runtimeBytecode)) {
    // The chain database was reset or the contract source changed: the old address is no longer StudyCoin.
    console.log('Previous local deployment not found on chain; deploying a new StudyCoin.');
    deployment = null;
  }
  if (!deployment) {
    const c = await new ContractFactory(compiled.abi, compiled.bytecode, new Wallet(s.admin.key, provider))
      .deploy(s.admin.address, s.operator.address);
    const receipt = await c.deploymentTransaction().wait();
    deployment = { chainId: 31337, contract: await c.getAddress(), transaction: receipt.hash,
      blockNumber: receipt.blockNumber, admin: s.admin.address, operator: s.operator.address, deployedAt: new Date().toISOString() };
    fs.writeFileSync(record, JSON.stringify(deployment, null, 2));
  }
  // Keep a previously generated worker secret and any Supabase keys the user already filled in.
  const previous = fs.existsSync(envFile) ? Object.fromEntries(fs.readFileSync(envFile, 'utf8').split(/\r?\n/)
    .filter(l => /^[A-Z_]+=/.test(l)).map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)])) : {};
  const keep = k => previous[k] || '';
  const lines = [
    '# Local StudyCoin backend config. Generated by blockchain/scripts/local-setup.mjs; never commit or share.',
    '# Fill the three SUPABASE_* values with the STAGING project (studymind-staging), never production.',
    `SUPABASE_URL=${keep('SUPABASE_URL')}`, `SUPABASE_ANON_KEY=${keep('SUPABASE_ANON_KEY')}`,
    `SUPABASE_SERVICE_ROLE_KEY=${keep('SUPABASE_SERVICE_ROLE_KEY')}`, `REWARDS_STAGING_PROJECT_REF=${keep('REWARDS_STAGING_PROJECT_REF')}`,
    'REWARDS_ENABLED=true', `REWARDS_RPC_URL=${LOCAL_RPC}`, 'REWARDS_CONFIRMATIONS=1',
    `REWARDS_TOKEN_ADDRESS=${deployment.contract}`, `REWARDS_OPERATOR_ADDRESS=${s.operator.address}`,
    `REWARDS_WALLET_XPUB=${s.walletXpub}`, `REWARDS_OPERATOR_KEY=${s.operator.key}`, `REWARDS_ADMIN_KEY=${s.admin.key}`,
    `REWARDS_WORKER_SECRET=${keep('REWARDS_WORKER_SECRET') || randomBytes(32).toString('hex')}`, ''];
  fs.writeFileSync(envFile, lines.join('\n'), { mode: 0o600 });
  console.log(JSON.stringify({ chainId: 31337, contract: deployment.contract, admin: s.admin.address,
    operator: s.operator.address, env: '.local/rewards-local.env' }, null, 2));
} finally { provider.destroy(); }
