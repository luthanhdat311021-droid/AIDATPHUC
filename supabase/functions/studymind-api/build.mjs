// Bundles src/main.js + backend/ into one index.ts for the Supabase Edge Function editor / CLI.
// npm packages stay external as Deno "npm:" imports; Node built-ins become "node:" imports.
// Run from the repo root: node supabase/functions/studymind-api/build.mjs
import { rolldown } from 'rolldown';
import { builtinModules } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const dir = path.dirname(fileURLToPath(import.meta.url));

const NPM = {
  'express': 'npm:express@5.2.1',
  '@google/generative-ai': 'npm:@google/generative-ai@0.24.1',
  'groq-sdk': 'npm:groq-sdk@1.6.0',
  'mammoth': 'npm:mammoth@1.12.3',
  'jszip': 'npm:jszip@3.10.2',
  '@supabase/supabase-js': 'npm:@supabase/supabase-js@2.116.0',
  'unpdf': 'npm:unpdf@1.8.1'
};

// Not usable (or not needed) on the edge: env comes from Supabase secrets, PDFs are read by unpdf,
// images by Gemini vision. Each stub keeps the existing fallbacks in documentParser.js working.
const STUBS = {
  'dotenv': 'export const config = () => ({}); export default { config };',
  'pdf-parse': 'export default undefined;',
  'tesseract.js': 'export default {};'
};

const edgePlugin = {
  name: 'edge-imports',
  resolveId(id) {
    if (STUBS[id] !== undefined) return `\0stub:${id}`;
    if (NPM[id]) return { id: NPM[id], external: true };
    const bare = id.replace(/^node:/, '');
    if (builtinModules.includes(bare.split('/')[0])) return { id: `node:${bare}`, external: true };
    return null;
  },
  load(id) {
    if (id.startsWith('\0stub:')) return STUBS[id.slice(6)];
    return null;
  }
};

const bundle = await rolldown({
  input: path.join(dir, 'src/main.js'),
  plugins: [edgePlugin],
  platform: 'neutral'
});
const { output } = await bundle.generate({
  format: 'esm',
  minify: true,
  codeSplitting: false,
  banner: '// @ts-nocheck\n// GENERATED by build.mjs from backend/ - edit the sources, not this file.\nimport process from "node:process";\nimport { Buffer } from "node:buffer";'
});
const code = output[0].code;
fs.writeFileSync(path.join(dir, 'index.ts'), code);
console.log(`index.ts: ${(code.length / 1024).toFixed(0)} KB, chunks: ${output.length}`);
